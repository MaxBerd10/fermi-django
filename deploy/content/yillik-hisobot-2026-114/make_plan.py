import json
import re
import subprocess
import time
from pathlib import Path

ops = []
cache = {}


def blocks_of(slug):
    if slug not in cache:
        for _ in range(5):
            text = subprocess.run(["curl", "-s", "--max-time", "90", "https://fermi.uz/api/v1/pages/%s/?v=114" % slug], capture_output=True, text=True).stdout
            try:
                cache[slug] = {b["order"]: b for b in json.loads(text)["blocks"]}
                break
            except ValueError:
                time.sleep(3)
    return cache[slug]


def put(slug, order, lang, new):
    block = blocks_of(slug)[order]
    field = "caption" if block["block_type"] == "document" else "text"
    old = block["data"][lang][field]
    if old != new:
        ops.append({"slug": slug, "order": order, "lang": lang, "field": field, "old": old, "new": new})


